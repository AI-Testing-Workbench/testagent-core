import path from "path"
import { fileURLToPath } from "url"

const __filename = fileURLToPath(import.meta.url)
const __dirname = path.dirname(__filename)
const dir = path.resolve(__dirname, "..")

process.chdir(dir)

// testagent_change start - add offline fallback for models.dev snapshot
const modelsUrl = process.env.OPENCODE_MODELS_URL || "https://models.dev"
// Fetch and generate models.dev snapshot
const existingSnapshot = path.join(dir, "src/provider/models-snapshot.js")
let modelsData: string
if (process.env.MODELS_DEV_API_JSON) {
  modelsData = await Bun.file(process.env.MODELS_DEV_API_JSON).text()
} else {
  try {
    modelsData = await fetch(`${modelsUrl}/api.json`).then((x) => x.text())
  } catch {
    console.warn(`Warning: Failed to fetch ${modelsUrl}/api.json, using existing snapshot`)
    const existingContent = await Bun.file(existingSnapshot).text()
    const match = existingContent.match(/export const snapshot = (\{[\s\S]*\})/)
    if (!match) throw new Error("No existing models-snapshot.js found and network fetch failed")
    modelsData = match[1]
  }
}
// testagent_change end
await Bun.write(
  path.join(dir, "src/provider/models-snapshot.js"),
  `// @ts-nocheck\n// Auto-generated by build.ts - do not edit\nexport const snapshot = ${modelsData}\n`,
)
await Bun.write(
  path.join(dir, "src/provider/models-snapshot.d.ts"),
  `// Auto-generated by build.ts - do not edit\nexport declare const snapshot: Record<string, unknown>\n`,
)
console.log("Generated models-snapshot.js")
